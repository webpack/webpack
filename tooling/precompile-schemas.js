"use strict";

// Compile every `schemas/**/*.json` into the standalone check webpack
// validates options with, as `schemas/**/*.check.js`.
//
//   node tooling/precompile-schemas.js          # report what is stale
//   node tooling/precompile-schemas.js --write  # write those checks
//
// WHY: webpack validates against generated code rather than carrying `ajv` at
// runtime, so the checks are committed and a check run names a stale one.
// `schema-utils` compiles them, the same way it compiles a plugin's or a
// loader's, so a check accepts exactly what the full validation accepts.
// `minify` minifies them with webpack's own minifier, so `webpack` must
// resolve to this repository (`yarn link && yarn link webpack`).
//
// It also writes the `// #region generator option keys` block in
// `lib/module/NormalModuleFactory.js`: the option keys each module type's
// `module.generator` entry accepts, so merging a parent type's options into a
// child type can drop what the child rejects without loading the schema.

const fs = require("fs");
const path = require("path");
const { pathToFileURL } = require("url");
const { globSync } = require("glob");
const { precompile } = require("schema-utils");
const argv = require("./argv");

/** @import { ExtendedSchema, JSONSchema7 } from "schema-utils" */

const { write: doWrite, root, schemas: schemasGlob } = argv;

/**
 * @param {string} path the file to compare against
 * @param {string} expected the content the file must hold
 * @returns {boolean} whether the file already holds it
 */
const updateFile = (path, expected) => {
	let normalizedContent = "";
	try {
		const content = fs.readFileSync(path, "utf8");
		normalizedContent = content.replace(/\r\n?/g, "\n");
	} catch (_err) {
		// ignore
	}
	if (normalizedContent.trim() === expected.trim()) return true;
	if (doWrite) {
		fs.writeFileSync(path, expected, "utf8");
		console.error(`${path} updated`);
		return true;
	}
	console.error(`${path} need to be updated\nExpected:\n${expected}`);
	return false;
};

/**
 * @param {string} schemaPath absolute path of the schema to precompile
 * @returns {Promise<boolean>} whether the check is up to date
 */
const precompileSchema = async (schemaPath) => {
	if (path.basename(schemaPath).startsWith("_")) return true;
	try {
		const schema = /** @type {JSONSchema7 & ExtendedSchema} */ (
			JSON.parse(fs.readFileSync(schemaPath, "utf8"))
		);
		// A relative `$ref` to another schema resolves against this one
		schema.$id = pathToFileURL(schemaPath).href;
		const code = await precompile(schema, { minify: true });
		return updateFile(schemaPath.replace(/\.json$/, ".check.js"), code);
	} catch (err) {
		const error = /** @type {Error} */ (err);

		error.message += `\nduring precompilation of ${schemaPath}`;
		throw error;
	}
};

const GENERATOR_KEYS_REGION_REGEXP =
	/\/\/ #region generator option keys\r?\n[\s\S]+?\/\/ #endregion\r?\n/;

/**
 * Renders the `// #region generator option keys` block: for each module type
 * whose `module.generator` entry is a closed object, the keys it accepts.
 * @param {JSONSchema7} schema the webpack options schema
 * @returns {string} the region
 */
const renderGeneratorOptionKeys = (schema) => {
	const definitions = /** @type {Record<string, JSONSchema7>} */ (
		schema.definitions
	);
	const byType = /** @type {Record<string, JSONSchema7>} */ (
		definitions.GeneratorOptionsByModuleType.properties
	);
	/** @type {Record<string, string[]>} */
	const keys = {};
	for (const type of Object.keys(byType).sort()) {
		const entry = byType[type];
		const definition = entry.$ref
			? definitions[entry.$ref.slice("#/definitions/".length)]
			: entry;
		if (definition.additionalProperties !== false) continue;
		keys[type] = Object.keys(definition.properties || {}).sort();
	}
	return `// #region generator option keys
// Auto-generated by \`tooling/precompile-schemas.js\` from
// \`schemas/WebpackOptions.json\` — run \`yarn fix:special\` to refresh.

// The option keys \`module.generator\` accepts for each module type the schema
// closes; a type it leaves open, or does not list, accepts any. Null-prototype,
// so a type named like an \`Object.prototype\` key does not read one.

// prettier-ignore
const GENERATOR_OPTION_KEYS = /** @type {Readonly<Record<string, readonly string[]>>} */ (Object.freeze(Object.assign(Object.create(null), ${JSON.stringify(keys)})));
// #endregion
`;
};

/**
 * @returns {boolean} whether the generator option keys region is up to date
 */
const updateGeneratorOptionKeys = () => {
	const schemaPath = path.resolve(root, "schemas/WebpackOptions.json");
	const target = path.resolve(root, "lib/module/NormalModuleFactory.js");
	if (!fs.existsSync(schemaPath) || !fs.existsSync(target)) return true;
	const source = fs.readFileSync(target, "utf8").replace(/\r\n?/g, "\n");
	if (!GENERATOR_KEYS_REGION_REGEXP.test(source)) {
		throw new Error(
			`Could not find the \`// #region generator option keys\` block in ${target}`
		);
	}
	const schema = /** @type {JSONSchema7} */ (
		JSON.parse(fs.readFileSync(schemaPath, "utf8"))
	);
	return updateFile(
		target,
		source.replace(
			GENERATOR_KEYS_REGION_REGEXP,
			renderGeneratorOptionKeys(schema)
		)
	);
};

const main = async () => {
	const schemaPaths = globSync(schemasGlob, {
		cwd: root,
		absolute: true
	}).sort();
	const results = await Promise.all(schemaPaths.map(precompileSchema));
	results.push(updateGeneratorOptionKeys());
	process.exitCode = results.every(Boolean) ? 0 : 1;
};

main().catch((/** @type {ThrownValue} */ err) => {
	console.error(err);
	process.exitCode = 1;
});
